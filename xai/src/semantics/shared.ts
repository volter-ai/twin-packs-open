import { openaiWire, type HandlerContext } from '@volter/world-core';

export type Row = Record<string, unknown>;
export const KEY = '_api_key';
const sha256 = (ctx: Pick<HandlerContext, 'crypto'>, v: string): string => ctx.crypto.digest('sha256', v, 'hex');

// ── keys ───────────────────────────────────────────────────────────────────────────────────────
// A key is `xai-` and 80 letters and digits; the World keeps it by its SHA-256 (the row's id is minted) and draws it from a secret it holds.

const keyValue = async (ctx: Pick<HandlerContext, 'secret' | 'crypto'>, label: string): Promise<string> =>
  `xai-${ctx.crypto.base62From(await ctx.secret(label), 80)}`;

// source: https://docs.x.ai/developers/rest-api-reference/management/auth.md
export async function keyTeam(ctx: HandlerContext): Promise<Row> {
  return ctx.tenant('_team', async (organization) => {
    const user = await ctx.createUnique('_user', { email: organization.members[0]!.toLowerCase() }, 'user.create', { input: 'omit' });
    return String((await ctx.create('_team', { name: organization.label, owner: user.row.id }, 'team.create')).id);
  });
}

export async function makeKey(ctx: HandlerContext, name: string, team: Row): Promise<string> {
  const id = await ctx.issue(KEY);
  const label = `xai-api-key:${id}`;
  const key = await keyValue(ctx, label);
  await ctx.record(KEY, { name, teamId: team.id, userId: team.owner, aclStrings: ['api-key:endpoint:*', 'api-key:model:*'], disabled: false, label, createTime: ctx.occurredAt, modifyTime: ctx.occurredAt, sha256: sha256(ctx, key) }, id);
  return id;
}

export async function readKey(ctx: HandlerContext, row: Row): Promise<string | undefined> {
  if (row.deleted === true || row.disabled === true || (typeof row.expireTime === 'string' && Date.parse(row.expireTime) <= Date.parse(ctx.occurredAt))) return undefined;
  const key = await keyValue(ctx, String(row.label));
  return sha256(ctx, key) === row.sha256 ? key : undefined;
}

