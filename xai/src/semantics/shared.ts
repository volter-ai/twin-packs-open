export const MODELS = new Set(['latest', 'grok-4.7', 'grok-4.6', 'grok-4.5', 'grok-4.3', 'grok-4.20', 'grok-4.20-0309-reasoning', 'grok-4.20-0309-non-reasoning', 'grok-4.20-multi-agent-0309', 'grok-build-0.1']);
/** Whether a model reasons: the models page's reasoning variants and the Grok 4.3 and later. Where the documentation
 *  stops: a model page says whether it reasons; the twin reads the non-reasoning name as the one that does not. */
export const reasons = (model: string): boolean => !model.includes('non-reasoning') && model !== 'grok-build-0.1' && model !== 'latest';
export const noModel = (model: string): Response => xaiError(404, 'Some requested entity was not found', `The model ${model} does not exist or your team does not have access to it.`);

export const obj = (v: unknown): Row => (v && typeof v === 'object' && !Array.isArray(v) ? v as Row : {});
export const arr = (v: unknown): Row[] => (Array.isArray(v) ? v as Row[] : []);
// source: spec:/components/schemas/ChoiceMessage/properties/reasoning_content "The reasoning trace generated by the model."
export const stubReasoning = (model: string, about: string): string | null => reasons(model) ? `[twin-stub] Reasoning about: ${about.slice(0, 120) || '(empty)'}` : null;
export const sse = (body: string): Response => new Response(body, { headers: { 'content-type': 'text/event-stream', 'cache-control': 'no-cache' } });

// source: spec:/components/schemas/Usage "Breakdown of prompt token usage of different types."
// Token estimates and zero synthetic costs describe the deterministic stub, not real billing.
export function chatUsage(shape: openaiWire.ChatShape): Row {
  const usage = obj(openaiWire.chatCompletion({ ...shape, usageExtra: undefined }).usage);
  const reasoning = Number(obj(usage.completion_tokens_details).reasoning_tokens);
  // source: spec:handle_generic_completion_request "101 multiplied by 3 is 303."
  // The xAI published Chat example counts reasoning separately from completion_tokens, in total_tokens.
  return { completion_tokens: Number(usage.completion_tokens) - reasoning, num_sources_used: 0, cost_in_usd_ticks: 0, prompt_tokens_details: { text_tokens: usage.prompt_tokens, audio_tokens: 0, image_tokens: 0, cached_tokens: 0 }, completion_tokens_details: { reasoning_tokens: reasoning, audio_tokens: 0, accepted_prediction_tokens: 0, rejected_prediction_tokens: 0 } };
}

// source: spec:/components/schemas/ModelResponse "Whether to process the response asynchronously in the background."
// source: spec:/components/schemas/ModelUsage "Number of server side tools used."
// source: https://docs.x.ai/developers/models.md "always returns"
// An encrypted trace is a labelled opaque placeholder; it does not represent model thinking.
export function responseView(answer: Row, body: Row): Row {
  const encrypted = body.model === 'grok-4.7' || (Array.isArray(body.include) && body.include.includes('reasoning.encrypted_content'));
  // the sampling and reasoning configuration as the request set it, null where it set none
  // source: spec:/components/schemas/ModelResponse/properties/reasoning "Reasoning configuration. Only for reasoning models."
  // Where the documentation stops: the fields' descriptions are the request's; the reference's 200 answer, to a request
  // that sets none of them, has temperature, top_p and reasoning null
  // A text's logprobs stay the array the schema types them as (the kernel's empty list, no model runs), never the
  // reference sample's null: the unchanged @ai-sdk/xai 4.0.54 refuses a null there ("expected array, received null")
  // source: spec:/components/schemas/OutputMessageContent "The log probabilities of each output token returned in the content of message."
  return { ...answer, temperature: body.temperature ?? null, top_p: body.top_p ?? null, reasoning: body.reasoning ?? null, background: false, service_tier: body.service_tier ?? 'default', truncation: 'disabled', top_logprobs: body.top_logprobs ?? 0, presence_penalty: 0, frequency_penalty: 0, user: body.user ?? null,
    output: arr(answer.output).map(item => item.type === 'reasoning' && encrypted ? { ...item, encrypted_content: '[twin-stub] opaque encrypted reasoning' } : item),
    usage: answer.usage === null ? null : { ...obj(answer.usage), num_sources_used: 0, num_server_side_tools_used: 0 } };
}

// source: spec:/components/schemas/ModelRequest/properties/stream "Tokens will be sent as data-only server-sent events"
export const responseStream = (stream: string, body: Row): string => stream.split('\n').map(line => {
  if (!line.startsWith('data: ')) return line;
  const event = JSON.parse(line.slice(6)) as Row;
  if (event.response) event.response = responseView(obj(event.response), body);
  if (obj(event.item).type === 'reasoning' && (body.model === 'grok-4.7' || (Array.isArray(body.include) && body.include.includes('reasoning.encrypted_content')))) event.item = { ...obj(event.item), encrypted_content: '[twin-stub] opaque encrypted reasoning' };
  return `data: ${JSON.stringify(event)}`;
}).join('\n');
