// Publishing (libnpmpublish). A package is one CouchDB document: a publish PUTs it with the new version and its tarball
// attached. npm's deprecate, owner and unpublish write the same document; no application here makes those writes
// (../../journeys/demand.json), so they are not served.
import type { HandlerContext } from '@volter/world-core';
import {
  attestationKey, attestationsUrl, blobKey, checkProvenance, fail, mayWrite, nameOf, ok, PACKAGE, packument, type Row, scopeOf, tarballFile, tarballUrl, provenanceFile, versionsOf, writer,
} from './shared.ts';

const bodyOf = (ctx: HandlerContext): Row => (ctx.body && typeof ctx.body === 'object' && !Array.isArray(ctx.body) ? ctx.body as Row : {});

/** Base64 to bytes (an attachment's `data`). */
function bytesOf(data: string): Uint8Array | undefined {
  // decoded natively: a tarball's base64 is megabytes, and a character-by-character decode copies it several times over
  const bytes = Buffer.from(data, 'base64');
  return bytes.length || !data ? new Uint8Array(bytes.buffer, bytes.byteOffset, bytes.byteLength) : undefined;
}

/** `PUT /{package}`: a publish, a version with its tarball attached. */
// source: https://raw.githubusercontent.com/npm/cli/v10.9.8/workspaces/libnpmpublish/lib/publish.js "const res = await npmFetch(spec.escapedName, {"
export async function libnpmpublish_publish(ctx: HandlerContext): Promise<Response> {
  const who = writer(ctx);
  if (who instanceof Response) return who;
  const name = nameOf(ctx.call.params.spec_escapedName);
  const body = bodyOf(ctx);
  const pkg = ctx.row(PACKAGE, name);
  // Where the documentation stops: the registry's permission refusal is not recorded; its message is npm's as its CLI
  // prints it for E403
  if (!mayWrite(ctx, who.user, name, pkg)) return fail(403, `You do not have permission to publish "${name}". Are you logged in as the correct user?`);
  const attachments = (body._attachments as Record<string, Row> | undefined) ?? {};
  const versions = (body.versions as Record<string, Row> | undefined) ?? {};
  // a document PUT with no attachment is npm deprecate's or npm owner's, which are not served
  if (Object.keys(attachments).length === 0) return fail(400, 'A publish attaches each version\'s tarball.');
  if (typeof body.name === 'string' && body.name !== name) return fail(400, `The package's name "${body.name}" is not the name it is published at, "${name}".`);
  const held = new Set(versionsOf(ctx, name).map((v) => String(v.version)));
  const published = Object.keys(versions);
  if (published.length === 0) return fail(400, 'A publish names at least one version.');
  // Where the documentation stops: the message is npm's for publishing over a version, as its CLI prints it
  const over = published.find((v) => held.has(v));
  if (over) return fail(403, `You cannot publish over the previously published versions: ${over}.`);
  const tarballs = new Map<string, Uint8Array>();
  for (const v of published) {
    // the attachment is keyed by the package's full name (a scoped one keeps its scope), not the tarball URL's file name
    // source: https://raw.githubusercontent.com/npm/cli/v10.9.8/workspaces/libnpmpublish/lib/publish.js "const tarballName = `${manifest.name}-${manifest.version}.tgz`"
    const file = `${name}-${v}.tgz`;
    const attachment = attachments[file] ?? attachments[tarballFile(name, v)];
    const bytes = typeof attachment?.data === 'string' ? bytesOf(attachment.data) : undefined;
    if (!bytes) return fail(400, `The tarball for ${name}@${v} is not attached (${file}).`);
    if (attachment!.length !== undefined && Number(attachment!.length) !== bytes.byteLength) return fail(400, `The tarball for ${name}@${v} is ${bytes.byteLength} bytes; the attachment says ${String(attachment!.length)}.`);
    tarballs.set(v, bytes);
  }
  // a version published with provenance carries its Sigstore bundle, checked before anything is kept
  const provenance = new Map<string, { predicateType: string; bundle: Row }>();
  for (const [v, bytes] of tarballs) {
    const attached = attachments[provenanceFile(name, v)];
    const checked = attached && typeof attached.data === 'string' ? await checkProvenance(ctx, name, v, bytes, versions[v]!, attached.data) : undefined;
    if (checked instanceof Response) return checked;
    if (checked) provenance.set(v, checked);
  }
  const npmUser = { name: who.user.name, email: who.user.email };
  const maintainers = (pkg?.maintainers as Row[] | undefined) ?? [npmUser];
  const time: Row = { ...((pkg?.time as Row | undefined) ?? { created: ctx.occurredAt }), modified: ctx.occurredAt };
  const allVersions: Record<string, Row> = { ...((pkg?.versions as Record<string, Row> | undefined) ?? {}) };
  for (const [v, bytes] of tarballs) {
    const file = tarballFile(name, v);
    await ctx.blobs.put(blobKey(name, file), bytes);
    // "The `dist` object is generated by npm and may be relied upon" (package-metadata.md): the url, sha1 and sha512
    // source: https://raw.githubusercontent.com/npm/registry/main/docs/responses/package-metadata.md "`shasum`: the SHA-1 sum of the tarball"
    const proven = provenance.get(v);
    const dist = {
      tarball: tarballUrl(name, v), shasum: ctx.crypto.digest('sha1', bytes, 'hex'), integrity: `sha512-${ctx.crypto.digest('sha512', bytes, 'base64')}`,
      // where the version's attestations are, and the provenance's type
      // source: https://raw.githubusercontent.com/npm/pacote/v19.0.2/lib/registry.js "if (dist.attestations) {"
      ...(proven ? { attestations: { url: attestationsUrl(name, v), provenance: { predicateType: proven.predicateType } } } : {}),
    };
    if (proven) await ctx.blobs.put(attestationKey(name, v), new TextEncoder().encode(JSON.stringify({ attestations: [proven] })));
    const { _attachments: _a, ...manifest } = versions[v]!;
    allVersions[v] = { ...manifest, name, version: v, _id: `${name}@${v}`, dist, _npmUser: npmUser, maintainers };
    time[v] = ctx.occurredAt;
  }
  // a scoped package is restricted unless published public; an unscoped one is always public (npm publish --access)
  const access = pkg?._access ?? (scopeOf(name) && body.access !== 'public' ? 'restricted' : 'public');
  const distTags = { ...((pkg?.['dist-tags'] as Row | undefined) ?? {}), ...((body['dist-tags'] as Row | undefined) ?? {}) };
  const previous = pkg ? packument(ctx, pkg, false) : {};
  const revision = Number(String(pkg?._rev ?? '0').split('-')[0]) + 1;
  // source: https://raw.githubusercontent.com/npm/registry/main/docs/responses/package-metadata.md "The following fields are hoisted to the top-level of the package json from the latest version published:"
  const latest = allVersions[published.at(-1)!] ?? {};
  const hoisted = Object.fromEntries(['author', 'bugs', 'contributors', 'description', 'homepage', 'keywords', 'license', 'readmeFilename', 'repository'].filter((k) => latest[k] !== undefined).map((k) => [k, latest[k]]));
  // source: https://raw.githubusercontent.com/npm/registry/main/docs/responses/package-metadata.md "the revision number of this version of the document in CouchDB"
  await ctx.write(PACKAGE, name, { ...previous, ...hoisted, _id: name, _rev: `${revision}-${ctx.crypto.digest('md5', `${name}:${revision}`, 'hex')}`, name, readme: body.readme ?? pkg?.readme ?? '', 'dist-tags': distTags, versions: allVersions, maintainers, time, _attachments: {}, _access: access }, 'libnpmpublish.publish');
  return ok();
}
