import { selectedPack } from './selected-pack.mjs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
const selected = selectedPack();
const pkg = selected.manifest;
const files = readdirSync(selected.release).filter((name) => name.endsWith('.tgz'));
assert.equal(files.length, 1, 'release contains exactly one immutable package');
const integrity = 'sha512-' + createHash('sha512').update(readFileSync(join(selected.release, files[0]))).digest('base64');
assert.ok(process.env.RUNNER_TEMP, 'publisher workflow supplies a disposable output directory');
const output = join(process.env.RUNNER_TEMP, 'catalog-submissions');
const prepared = spawnSync(process.execPath, [process.env.CATALOG_CLI ?? 'node_modules/@volter/twin-catalog/bin/twin-catalog.mjs', 'submit', '--confirm-published', '--source', 'twin-packs-open', '--vendor', selected.vendor, '--package', pkg.name, '--version', pkg.version, '--out-dir', output], { encoding: 'utf8' });
assert.equal(prepared.status, 0, prepared.stderr);
const result = JSON.parse(prepared.stdout);
assert.equal(result.submission.integrity, integrity, 'registry bytes differ from the uploaded release');
console.log(JSON.stringify(result, null, 2));
